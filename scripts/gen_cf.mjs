// Generates src/data/cf.js from the Codeforces API (usage: node scripts/gen_cf.mjs [problemset.json])
import { readFileSync, writeFileSync } from 'node:fs';
const src = process.argv[2];
const json = src ? JSON.parse(readFileSync(src, 'utf8')) : await (await fetch('https://codeforces.com/api/problemset.problems')).json();
const { problems, problemStatistics } = json.result;
const solved = new Map(problemStatistics.map(s => [s.contestId + s.index, s.solvedCount]));
const RATINGS = [800, 900, 1000, 1100, 1200, 1300, 1400, 1500, 1600];
const PER = 24, CAP = 7; // per tag cap keeps ladders diverse
const BLURB = {
  800: 'First steps: read carefully, simulate, print.', 900: 'Simple observations and tidy implementation.',
  1000: 'Small tricks and basic greedy or math.', 1100: 'Greedy, sorting and constructive thinking.',
  1200: 'Where patterns start to matter.', 1300: 'Binary search, prefix sums, two pointers.',
  1400: 'Real algorithmic ideas appear.', 1500: 'Solid Div2 C/D territory.', 1600: 'Pupil to Specialist push.',
};
const ok = p => p.type === 'PROGRAMMING' && p.contestId < 10000 && !p.tags.some(t => t.includes('special'));
const ladders = RATINGS.map(r => {
  const pool = problems.filter(p => p.rating === r && ok(p) && solved.get(p.contestId + p.index) > 0)
    .sort((a, b) => solved.get(b.contestId + b.index) - solved.get(a.contestId + a.index));
  const cnt = {}, pick = [];
  for (const p of pool) {
    if (pick.length >= PER) break;
    const t = p.tags[0] || 'misc';
    if ((cnt[t] || 0) >= CAP) continue;
    cnt[t] = (cnt[t] || 0) + 1; pick.push(p);
  }
  // easy-to-hard proxy: most solved first
  return {
    id: String(r), label: String(r), blurb: BLURB[r],
    problems: pick.map(p => ({ id: p.contestId + p.index, contest: p.contestId, index: p.index, name: p.name, rating: r, tags: p.tags,
      url: `https://codeforces.com/problemset/problem/${p.contestId}/${p.index}` })),
  };
});
const out = `// Generated by scripts/gen_cf.mjs from the Codeforces API. Do not edit by hand.
export const CF_LADDERS = ${JSON.stringify(ladders, null, 1)};
export const CF_ALL = CF_LADDERS.flatMap(l => l.problems);
export const CF_BY_ID = Object.fromEntries(CF_ALL.map(p => [p.id, p]));
export const CF_LADDER_BY_ID = Object.fromEntries(CF_LADDERS.map(l => [l.id, l]));
export const CF_TAGS = [...new Set(CF_ALL.flatMap(p => p.tags))].sort();
/** Codeforces rating tier colour key. */
export const cfTier = r => (r < 1200 ? 'gray' : r < 1400 ? 'green' : r < 1600 ? 'cyan' : r < 1900 ? 'blue' : 'purple');
`;
writeFileSync(new URL('../src/data/cf.js', import.meta.url), out);
