# Regenerates problems.js from the switch-prep tracker's DSA sheet.
# Usage: python3 scripts/extract.py "/path/to/switch_prep_tracker.xlsx"
import json, re, sys, openpyxl

wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
items = []
for r in wb['DSA'].iter_rows(min_row=2, values_only=True):
    if not r[4]:
        continue
    week, dates, topic, n, item, diff, status, _done, _rev, _t, note, kind, link = r[:13]
    items.append({
        'n': int(n), 'week': int(week), 'dates': dates, 'topic': topic,
        'title': re.sub(r'^Learn:\s*', '', item), 'kind': kind,
        'diff': diff, 'done': status == 'Done', 'note': note, 'url': link,
    })
out = 'problems.js'
with open(out, 'w') as f:
    f.write('// Generated by scripts/extract.py from the DSA sheet. Do not edit by hand.\n')
    f.write('window.ITEMS = [\n' + ',\n'.join(json.dumps(i, ensure_ascii=False) for i in items) + '\n];\n')
print(len(items), 'items ->', out)
